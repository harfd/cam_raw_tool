import { test, expect } from '@playwright/test';
import path from 'node:path';
import { readFile } from 'node:fs/promises';
test('NEF 导入、预览、风格切换、双模式导出与设置', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: '导入 NEF 照片' }).click();
  await page.getByLabel('NEF 文件').setInputFiles(path.resolve('DSC_0002.NEF'));
  await page.getByLabel('XMP 模板').setInputFiles(path.resolve('DSC_0002.xmp'));
  await page.getByRole('button', { name: '导入并分析原片' }).click();
  await expect(page.getByAltText('原始解码预览')).toBeVisible({ timeout: 40000 });
  await expect(page.getByAltText('调整后近似预览')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'DSC_0002.NEF' })).toBeVisible();
  await page.getByRole('button', { name: '电影感 冷暖对比' }).click();
  await page.locator('#strength').fill('0.5');
  await expect(page.locator('#preset-name')).toHaveValue('AI 电影感');
  await page.getByRole('button', { name: '通用风格' }).click();
  await expect(page.locator('#Exposure2012')).toHaveCount(0);
  await expect(page.locator('#Contrast2012')).toHaveValue('9');
  await page.locator('summary').filter({hasText:'颜色混合器 · HSL'}).click();
  await page.locator('#HueAdjustmentGreen').fill('-24');
  await page.getByRole('button',{name:'饱和度',exact:true}).click();
  await page.locator('#SaturationAdjustmentBlue').fill('-18');
  await page.locator('summary').filter({hasText:/^校准$/}).click();
  expect((await page.getByLabel('红原色 · 色相数值',{exact:true}).boundingBox())!.width).toBeLessThanOrEqual(70);
  await page.getByLabel('红原色 · 色相数值',{exact:true}).fill('18');
  await page.getByLabel('红原色 · 色相数值',{exact:true}).press('Tab');
  await page.locator('summary').filter({hasText:/^曲线$/}).click();
  await page.getByRole('button',{name:'蓝',exact:true}).click();
  await page.getByRole('button',{name:'添加点',exact:true}).click();
  await page.getByLabel('曲线输出',{exact:true}).fill('145');
  await page.getByLabel('曲线输出',{exact:true}).press('Tab');
  await expect(page.getByText('曲线已修改，尚未应用。')).toBeVisible();
  await page.getByRole('button',{name:'应用曲线',exact:true}).click();
  await page.locator('#ParametricLights').fill('12');
  await page.locator('#strength').fill('0.4');
  await expect(page.locator('#RedHue')).toHaveValue('18');
  await expect(page.getByText('正在更新预览…')).toHaveCount(0);
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: '导出 XMP 预设' }).click()]);
  await download.saveAs(path.resolve('work/ui-export.xmp'));
  const xml=await readFile(path.resolve('work/ui-export.xmp'),'utf8');
  expect(xml).toContain('crs:RedHue="18"');
  expect(xml).toContain('crs:HueAdjustmentGreen="-24"');
  expect(xml).toContain('crs:SaturationAdjustmentBlue="-18"');
  expect(xml).toContain('crs:ParametricLights="12"');
  expect(xml).toMatch(/<crs:ToneCurvePV2012Blue>[\s\S]*?<rdf:li>128, 145<\/rdf:li>/);
  await page.screenshot({ path: 'work/ui-workspace.png', fullPage: true });
  await page.getByRole('button', { name: '模型与 API 设置' }).click();
  await expect(page.locator('#model')).toHaveValue('deepseek-flash');
  await expect(page.locator('#base-url')).toHaveValue('https://api.deepseek.com');
  await page.getByRole('button', { name: '关闭设置' }).click();
  expect(errors).toEqual([]);
});
